# -*- coding: utf-8 -*-
"""가이드 2곳 보강 — 남은 1,200자 미만 페이지.

두 글 다 내용은 조밀하고 좋지만 분량이 짧다(1,080·1,183자).
랜딩과 겹치지 않는 주제만 고른다:
  slide-puzzle → 왜 반드시 풀 수 있는 판만 나오는가(패리티)
  color-sort   → 이동 수 줄이기·되돌리기 판단 (4/6/8색 얘기는 랜딩이 이미 다룸)

슬라이딩 퍼즐 주장은 구현으로 확인함: slShuffleTiles()가 완성 상태에서 시작해
실제로 가능한 이동만 K번 반복하므로 그 경로를 거꾸로 되짚으면 항상 완성으로 돌아간다.
"""
import io, re

ADD = {}

ADD['guide/slide-puzzle'] = """
    <h2>왜 이 게임엔 못 푸는 판이 없을까</h2>
    <p>슬라이딩 퍼즐에는 <b>영원히 풀 수 없는 배열</b>이 존재합니다. 그것도 드물게가 아니라, 조각을 늘어놓는 모든 방법의 정확히 절반이 그렇습니다. 15퍼즐에서 조각 두 개의 자리만 손으로 맞바꿔 놓으면, 남은 평생을 밀어도 완성되지 않는 판이 됩니다.</p>
    <p>이유는 간단합니다. 빈칸을 한 번 움직이는 것은 조각 하나와 빈칸의 자리를 맞바꾸는 일이고, 이 맞바꿈을 아무리 반복해도 넘어갈 수 없는 벽이 있습니다. 완성 상태에서 도달할 수 있는 배열과, 조각 두 개를 바꿔치기한 배열은 서로 다른 세계에 속합니다.</p>
    <p>Mallow의 슬라이딩 퍼즐은 <b>완성된 상태에서 시작해 실제로 가능한 이동만 여러 번 반복해</b> 판을 만듭니다. 그러니 어떤 판이든 그 이동을 거꾸로 되짚기만 하면 반드시 완성으로 돌아갑니다. <b>막히는 판은 나오지 않습니다.</b> 손이 막힌 것이지 판이 막힌 것이 아닙니다.</p>
    <div class="tip">💡 <b>확인해 보는 법</b> — 종이에 그려 푸는 15퍼즐 문제 중에는 애초에 답이 없는 것이 섞여 있습니다. 인터넷에서 배열만 베껴 와 풀리지 않는다면 실력 문제가 아닐 수 있습니다.</div>

    <h2>막혔을 때 되짚어 볼 세 가지</h2>
    <ul>
      <li><b>완성한 줄을 통과하는 경로로 빈칸을 돌리고 있지 않은가.</b> 가장 흔한 실수입니다. 빈칸을 옮길 때는 잠근 줄을 우회하는 경로만 씁니다.</li>
      <li><b>마지막 두 조각을 제자리에 하나씩 밀어 넣으려 하고 있지 않은가.</b> 그렇게는 들어가지 않습니다. 반드시 세워서 함께 회전시켜야 합니다.</li>
      <li><b>2×2만 남았는데 안 돌아가는가.</b> 마지막 2×2는 한 방향으로 계속 돌리기만 하면 됩니다. 두 조각이 서로 자리를 바꾼 것처럼 보인다면, 앞 단계에서 잠근 줄이 한 칸 어긋난 것입니다. 그 줄부터 다시 보세요.</li>
    </ul>
"""

ADD['guide/color-sort'] = """
    <h2>이동 수를 줄이는 두 가지</h2>
    <p>점수는 시간뿐 아니라 이동 수로도 깎입니다. 같은 판을 풀어도 수를 줄이면 점수가 확 달라집니다.</p>
    <ul>
      <li><b>한 번에 갈 수 있는 만큼 몰아서 옮기세요.</b> 같은 색이 위에 두세 칸 쌓여 있으면 통째로 이동합니다. 반대로 한 칸씩 나눠 옮기면 이동 수만 늘고 얻는 건 같습니다. 옮기기 전에 "지금 몇 칸이 함께 가는가"를 확인하는 습관만으로 수가 눈에 띄게 줄어듭니다.</li>
      <li><b>왕복을 만들지 마세요.</b> 빈 병에 잠깐 덜어 놨다가 다시 가져오는 이동은 두 수를 쓰고 아무것도 진전시키지 못합니다. 빈 병을 쓰기 전에 "이걸 다시 꺼낼 곳이 정해져 있나"를 물어보면 왕복이 사라집니다.</li>
    </ul>

    <h2>되돌리기는 언제 쓰는 게 이득인가</h2>
    <p>되돌리기도 이동 수에 포함되므로 무한정 쓸 수는 없습니다. 쓸 값어치가 있는 순간은 정해져 있습니다.</p>
    <ul>
      <li><b>빈 병을 잘못 쓴 직후</b> — 가장 확실하게 이득입니다. 한 수만 무르면 판 전체의 선택지가 돌아옵니다. 나중에 깨닫고 되돌리려면 훨씬 많은 수를 써야 합니다.</li>
      <li><b>완성 직전 병을 덮어 버린 직후</b> — 그대로 두면 그 병을 다시 파내느라 서너 수가 더 듭니다.</li>
      <li><b>반대로, 이미 여러 수가 지난 뒤</b>에는 되돌리기보다 지금 판에서 최선을 찾는 편이 낫습니다. 되돌리기 횟수를 다 쓰고도 원래 지점에 못 돌아가는 경우가 많습니다.</li>
    </ul>
    <div class="tip">💡 <b>습관 하나</b> — 부으려는 병을 누르기 전에 그 색이 <b>다음에 어디로 갈지</b>를 한 번만 떠올려 보세요. 갈 곳이 떠오르지 않으면 그 이동은 대개 나중에 무르게 됩니다.</div>
"""

for page, block in ADD.items():
    f = page + '/index.html'
    s = io.open(f, encoding='utf-8', newline='').read()
    key = re.search(r'<h2>([^<]+)</h2>', block).group(1)
    assert key not in s, '%s: 이미 적용됨' % page
    i = s.index('  </article>')
    s = s[:i] + block.strip('\n') + '\n' + s[i:]
    io.open(f, 'w', encoding='utf-8', newline='').write(s)
    print('ok %-22s +%d자' % (page, len(re.sub(r'<[^>]*>', '', block).strip())))
