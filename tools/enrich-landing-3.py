def inject(page, block):
    f = os.path.join(page, 'index.html')
    s = io.open(f, encoding='utf-8', newline='').read()
    key = re.search(r'<h2>([^<]+)</h2>', block).group(1)
    assert key not in s, '%s: 이미 적용됨(%s)' % (page, key)
    m = re.search(r'\n  <section><h2>자주 묻는 질문</h2>', s)
    i = m.start() + 1 if m else s.index('</main>')
    s = s[:i] + block.strip('\n') + '\n' + s[i:]
    io.open(f, 'w', encoding='utf-8', newline='').write(s)
    print('ok %-10s +%d자' % (page, len(re.sub(r'<[^>]*>', '', block).strip())))


for page, block in BLOCKS.items():
    inject(page, block)
