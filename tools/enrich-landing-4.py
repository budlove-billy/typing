# -*- coding: utf-8 -*-
"""모아모아 보강 — 규칙 설명은 충분하나 '어떻게 푸는가'가 없다.

다른 랜딩과 달리 moamoa는 seo-info 섹션 안에 h3로 구성돼 있으므로
같은 레벨(h3)로 FAQ 바로 앞에 끼운다.
"""
import io, re

BLOCK = """
    <h3>함정을 피하는 순서</h3>
    <p>이 퍼즐이 어려운 이유는 낱말을 몰라서가 아니라, <strong>여러 그룹에 다 어울리는 낱말</strong>이 일부러 섞여 있기 때문입니다. 그래서 “확실해 보이는 넷”을 바로 내는 것이 가장 흔한 실패 방식입니다.</p>
    <ol>
      <li><strong>먼저 다섯 개 이상을 세어 보세요.</strong> 어떤 공통점이 떠올랐을 때 거기 들어갈 후보가 다섯 개 넘게 보인다면, 그중 하나 이상은 다른 그룹의 낱말입니다. 아직 낼 때가 아닙니다.</li>
      <li><strong>남는 낱말부터 붙이세요.</strong> 어느 그룹에도 잘 안 어울리는 낱말을 먼저 찾아 그것이 들어갈 자리를 정하면, 나머지 그룹의 경계가 자동으로 선명해집니다.</li>
      <li><strong>가장 확신하는 그룹을 첫 시도로 쓰세요.</strong> 기회에는 한도가 있습니다. 반쯤 확신하는 조합을 던져 보며 정보를 얻으려 하면 대개 기회가 먼저 떨어집니다.</li>
    </ol>

    <h3>“하나만 달라요”를 제대로 쓰는 법</h3>
    <p>이 안내가 나왔다는 것은 넷 중 셋이 같은 그룹이라는 뜻입니다. 여기서 낱말 하나만 바꿔 다시 내면 되는데, <strong>어느 하나를 바꿀지</strong>가 핵심입니다.</p>
    <p>가장 의심스러운 자리는 “내가 제일 자신 있었던 낱말”인 경우가 많습니다. 그런 낱말일수록 다른 그룹에서 끌어온 미끼로 배치돼 있기 때문입니다. 반대로 넷 중 가장 평범하고 눈에 안 띄던 낱말이 보통 진짜 소속입니다.</p>

    <h3>자주 나오는 연결 고리</h3>
    <p>공통점은 뜻이 비슷한 말에만 있지 않습니다. 막혔을 때 아래를 차례로 대 보면 길이 열리는 경우가 많습니다.</p>
    <ul>
      <li><strong>앞이나 뒤에 같은 글자를 붙일 수 있는 말</strong> — 낱말 자체보다 합성어가 되는지를 봅니다.</li>
      <li><strong>같은 범주에 속하는 것</strong> — 음식, 악기, 색, 직업처럼 사전적으로 묶이는 묶음입니다.</li>
      <li><strong>속담이나 관용구의 한 조각</strong> — 낱말만 보면 관계없어 보여도 같은 표현에서 왔을 수 있습니다.</li>
      <li><strong>소리는 같지만 뜻이 다른 말</strong> — 보라 그룹에서 가장 자주 쓰이는 방식입니다. 눈에 보이는 뜻 말고 다른 뜻이 있는지 의심해 보세요.</li>
    </ul>
    <p>보라가 함정 그룹인 이유도 여기 있습니다. 노랑·초록·파랑을 먼저 걷어 내고 남은 넷이 보라라는 점을 이용하면, 보라를 직접 알아맞히지 않고도 완성할 수 있습니다.</p>
"""

f = 'moamoa/index.html'
s = io.open(f, encoding='utf-8', newline='').read()
assert '함정을 피하는 순서' not in s, '이미 적용됨'
anchor = '    <h3>자주 묻는 질문</h3>'
assert anchor in s, 'FAQ 앵커 없음'
s = s.replace(anchor, BLOCK.strip('\n') + '\n\n' + anchor, 1)
io.open(f, 'w', encoding='utf-8', newline='').write(s)
print('ok moamoa +%d자' % len(re.sub(r'<[^>]*>', '', BLOCK).strip()))
