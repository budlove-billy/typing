# -*- coding: utf-8 -*-
"""타로 한국어 본문 보강 — 렌더 950자로 사이트에서 가장 얇은 실제 페이지.

기존 ko 섹션은 규칙 설명(오늘의 카드·3카드·아르카나·이용법·FAQ)까지만 있다.
그다음에 필요한 것 — 네 슈트가 각각 무엇을 말하는지, 역방향을 어떻게 읽는지,
세 장을 하나의 이야기로 읽는 법 — 을 넣는다.

용어는 페이지가 실제로 화면에 쓰는 표기를 그대로 쓴다:
  슈트 완드(열정·일·행동)·컵(감정·사랑·관계)·소드(생각·갈등·결단)·펜타클(현실·돈·성취)
  주제 연애·일·학업·재물 / 자리 지난 인연·지금의 마음·다가올 사랑 등
"""
import io, re

BLOCK = """
    <div class="card">
      <h2>네 슈트가 말하는 것</h2>
      <p>마이너 아르카나 56장은 네 갈래로 나뉘고, 어떤 슈트가 많이 나왔는지만 봐도 지금 무엇이 마음을 차지하고 있는지 대강 읽힙니다.</p>
      <ul class="zlist">
        <li><b>완드</b> 열정 · 일 · 행동 — 하고 싶은 마음과 그것을 밀고 나가는 힘</li>
        <li><b>컵</b> 감정 · 사랑 · 관계 — 사람 사이에서 오가는 마음</li>
        <li><b>소드</b> 생각 · 갈등 · 결단 — 머릿속에서 벌어지는 일과 잘라내야 할 것</li>
        <li><b>펜타클</b> 현실 · 돈 · 성취 — 손에 잡히는 결과와 쌓이는 것</li>
      </ul>
      <p class="sub">세 장 중 두 장 이상이 같은 슈트라면 그쪽이 지금의 중심입니다. 이를테면 소드가 몰려 나왔다면, 상황이 나빠서라기보다 아직 생각 단계에 머물러 있다는 뜻으로 읽는 편이 맞습니다.</p>
    </div>
    <div class="card">
      <h2>역방향은 나쁜 카드가 아닙니다</h2>
      <p>카드가 뒤집혀 나오면 흔히 흉으로 여기지만, 대부분은 <b>같은 성질이 지나치거나 아직 때가 아니라는 신호</b>에 가깝습니다.</p>
      <p>예를 들어 열정을 뜻하는 카드가 역방향이면 열정이 사라졌다기보다 너무 앞서 나가 지쳤다는 쪽이고, 안정과 결실을 뜻하는 카드가 역방향이면 실패했다기보다 아직 익지 않았다는 쪽입니다. 그래서 역방향 카드는 예언보다 <b>속도를 조절하라는 조언</b>으로 받아들이면 훨씬 쓸모가 있습니다.</p>
      <p class="sub">세 장 가운데 둘 이상이 역방향이라면, 지금은 밀어붙일 때가 아니라 기다리는 편이 나은 시기로 봅니다.</p>
    </div>
    <div class="card">
      <h2>3카드를 읽는 네 단계</h2>
      <ol>
        <li><b>질문을 좁힙니다.</b> “잘될까요”는 카드가 답하기에 너무 넓습니다. “이 일을 이번 달에 어떻게 대하면 좋을까”처럼 기간과 태도를 담으면 세 자리가 각각 제 몫을 합니다.</li>
        <li><b>세 장을 이어서 읽습니다.</b> 한 장씩 따로 해석하면 서로 어긋난 세 개의 점괘가 됩니다. 첫 장이 둘째 장으로 어떻게 이어지는지, 셋째 장이 그 결과인지 아니면 갈림길인지를 보세요.</li>
        <li><b>자리의 뜻을 먼저 봅니다.</b> 연애라면 지난 인연·지금의 마음·다가올 사랑, 일·학업이라면 지나온 노력·현재 상황·앞으로의 흐름, 재물이라면 과거의 재물운·현재의 흐름·다가올 기회입니다. 같은 카드도 어느 자리에 놓였는지에 따라 다르게 읽힙니다.</li>
        <li><b>처음 든 느낌을 적어 둡니다.</b> 설명을 읽기 전에 카드를 봤을 때 스친 생각이, 대개 이미 알고 있었지만 꺼내지 않았던 답입니다.</li>
      </ol>
    </div>
    <div class="card">
      <h2>같은 질문을 다시 뽑아도 될까</h2>
      <p>3카드 스프레드는 뽑을 때마다 새로 나오기 때문에 몇 번이든 다시 볼 수 있습니다. 다만 <b>마음에 드는 답이 나올 때까지 다시 뽑는 것</b>은 읽는 일 자체를 무의미하게 만듭니다.</p>
      <p>결과가 마뜩잖다면 카드를 바꾸지 말고 질문을 바꿔 보세요. “헤어질까요” 대신 “지금 내가 놓치고 있는 게 뭘까”처럼 물으면, 같은 상황에서도 훨씬 쓸 만한 답이 나옵니다. 오늘의 카드가 하루 동안 고정되는 것도 같은 이유입니다 — 하루에 한 번은 그 카드를 그대로 안고 지내 보라는 뜻입니다.</p>
    </div>
"""

f = 'tarot/index.html'
s = io.open(f, encoding='utf-8', newline='').read()
assert '네 슈트가 말하는 것' not in s, '이미 적용됨'

# ko 섹션 안, '자주 묻는 질문' 카드 바로 앞에 끼운다
ko_start = s.index('<section class="seo" data-lang-only="ko">')
ko_end = s.index('</section>', ko_start)
anchor = s.index('<div class="card">\n      <h2>자주 묻는 질문</h2>', ko_start)
assert ko_start < anchor < ko_end, 'ko 섹션 안의 FAQ를 찾지 못함'
i = s.rindex('    <div class="card">', ko_start, anchor + 1)

s = s[:i] + BLOCK.strip('\n') + '\n' + s[i:]
io.open(f, 'w', encoding='utf-8', newline='').write(s)
print('ok tarot ko +%d자' % len(re.sub(r'<[^>]*>', '', BLOCK).strip()))
